	<p class="eyebrow">ÜBER JULIA</p>
	<h1>Betriebswirtin, Projektmanagerin, Teamplayerin.</h1>
	<p class="content-lede">
		Ich glaube daran, dass gute Organisation und echtes Engagement den Unterschied machen. Ob im
		Hörsaal, im Ehrenamt oder im Job: Ich übernehme Verantwortung, bringe Menschen zusammen und
		arbeite mit Herz und Struktur an Lösungen, die wirken.
	</p>


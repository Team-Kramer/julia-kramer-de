				<p>
					Ehrenamt ist für mich kein Extra – es ist Teil meines Lebens. Ob als Vorsitzende eines
					Jugendvereins, als Trainerin für Projektmanagement oder als Mitglied im Beirat der Civil
					Academy: Ich habe gelernt, wie man Teams führt, Ideen umsetzt und junge Menschen begeistert.
					Das hat mich geprägt – und mir gezeigt, wie viel möglich ist, wenn man einfach anfängt.
				</p>

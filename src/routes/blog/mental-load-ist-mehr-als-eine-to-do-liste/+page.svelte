	<h1 class="article-title">Mental Load ist mehr als eine To-do-Liste</h1>
	<p class="article-meta">Ein Modell, um unsichtbare Arbeit genauer zu sehen</p>

	<div class="prose">
		<p class="content-lede">
			Eine Aufgabe wirkt oft klein, wenn man nur den Moment betrachtet, in dem sie erledigt wird.
			Doch davor und danach liegt Arbeit, die auf einer Liste kaum auftaucht.
		</p>

		<h2>Die Aufgabe beginnt beim Bemerken</h2>
		<p>
			Der Vorrat geht zur Neige. Ein Termin muss vereinbart werden. Ein Kind braucht etwas für
			morgen. Bevor jemand handelt, muss häufig erst auffallen, dass etwas ansteht. Dann folgen
			Planung, Erinnerung, Abstimmung und schließlich das Erledigen.
		</p>
		<p>
			Wenn nur der letzte Schritt sichtbar ist, bleibt ein großer Teil der Verantwortung unsichtbar.
			Wer die Aufgabe ausführt, ist nicht automatisch auch die Person, die sie entdeckt, vorbereitet
			und bis zum Abschluss im Blick behält.
		</p>

		<div class="article-callout">
			<p><strong>Eine hilfreiche Frage:</strong> Wer bemerkt es, wer plant es, wer erledigt es – und wer prüft, ob es geklappt hat?</p>
		</div>

		<h2>Vier Schritte statt einer Aufgabe</h2>
		<ul>
			<li><strong>Bemerken:</strong> Was muss getan oder entschieden werden?</li>
			<li><strong>Planen:</strong> Wann, wie und mit welchen Mitteln passt es?</li>
			<li><strong>Erledigen:</strong> Wer übernimmt die konkrete Handlung?</li>
			<li><strong>Nachhalten:</strong> Muss jemand erinnern, prüfen oder neu abstimmen?</li>
		</ul>
		<p>
			Diese Schritte müssen nicht immer bei verschiedenen Menschen liegen. Sichtbar zu machen, wer
			welchen Teil trägt, kann aber ein Gespräch verändern: weg von „Hilf mir mehr“ und hin zu
			konkreten Zuständigkeiten, die nicht an eine einzelne Person gebunden sind.
		</p>

		<h2>Sichtbarkeit vor Bewertung</h2>
		<p>
			Das Modell ist kein Maßstab dafür, wer genug tut. Es ist eine Möglichkeit, Arbeit genauer zu
			beschreiben. Wenn etwas regelmäßig im Kopf einer Person bleibt, ist das eine Information über
			die Verteilung – kein persönliches Versagen.
		</p>
		<p>
			Der <a href="/werkzeuge/mental-load-check/">Mental-Load-Check</a> bietet einen ersten,
			privaten Blick auf organisatorischen, emotionalen und antizipierenden Load.
		</p>
	</div>

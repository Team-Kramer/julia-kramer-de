	<p class="eyebrow">TIEFER EINSTEIGEN</p>
	<h1>Manches lässt sich gemeinsam klarer sortieren.</h1>
	<p class="content-lede">
		Die Werkzeuge im Labor sind ein Anfang. Manchmal hilft es, die eigene Situation in Ruhe mit
		einer anderen Person anzuschauen und daraus passende nächste Schritte abzuleiten.
	</p>

	<div class="prose">
		<h2>Begleitung statt Schnelllösung</h2>
		<p>
			Ein mögliches Angebot ist ein Mental-Load-Audit: gemeinsam sichtbar machen, welche Aufgaben,
			Entscheidungen und unsichtbaren Zuständigkeiten gerade getragen werden. Daraus können
			alltagstaugliche Absprachen und Systeme entstehen.
		</p>
		<p>
			Das Angebot und die Kontaktmöglichkeit werden derzeit ausgearbeitet. Hier gibt es keine
			automatische Buchung und keine Warteliste. Die öffentlichen Werkzeuge bleiben unabhängig davon
			kostenlos nutzbar.
		</p>
	</div>
